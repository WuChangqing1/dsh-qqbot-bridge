// Boots the bridge through DSH's OWN boot path and checks what a real operator
// would see.
//
// `boot()` from `@deepseek-ai/dsh-app-boot` is the function `dsh web` itself
// runs: it creates the Context, installs the Cordis Loader, mounts the config
// through the Include builtin, settles the tree and audits activation. So this
// file exercises the real decision -- "is the entry active?" -- rather than a
// hand-mounted plugin, and it does so with a stub standing in for the QQ
// gateway, which keeps the test offline and never opens a second connection.
//
// It pins the two properties this project was missing:
//   1. a successful activation is VISIBLE (on the console, and in
//      `<dataDir>/bridge-status.json`);
//   2. a service that never arrives is ANNOUNCED, by name, instead of hanging
//      in silence the way a declared-but-absent `inject` does.

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { existsSync } from 'node:fs'
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { join, relative, sep } from 'node:path'

import { BRIDGE_ROOT, appBootSkip, loadAppBoot } from './cordis-harness.mjs'
import { sampleState } from './harness.mjs'

const skip = appBootSkip

let fixtures = 0

/**
 * Build a throwaway config tree that mounts one stub host provider plus THIS
 * project's real plugin entry.
 *
 * The fixture has to live inside the project: a `cordis.yml` entry names the
 * plugin with a relative specifier (the Include builtin resolves relative names
 * against the config directory and rejects an absolute path), and this machine's
 * temp directory sits on a different drive.
 *
 * @param {{withQqbot: boolean, watchdogIntervalMs?: number}} options
 */
const makeFixture = async ({ withQqbot, watchdogIntervalMs }) => {
  fixtures += 1
  const dir = join(BRIDGE_ROOT, `.loader-fixture-${process.pid}-${fixtures}`)
  const dataDir = join(dir, 'data')
  const statePath = join(dir, 'state.json')
  await mkdir(dir, { recursive: true })
  await writeFile(statePath, JSON.stringify(sampleState(), null, 2), 'utf8')

  const qqbot = withQqbot
    ? `
  ctx.provide('qqbot', {
    sender: { sendMarkdown: async () => ({}) },
    manager: {},
    config: { appId: 'stub' },
    replyTargetFor: (scope, targetId) => ({ scope, targetId }),
    setMessagePreHandler: () => () => {},
    get preHandlerCount() { return 1 },
  })
`
    : ''

  await writeFile(join(dir, 'stub.mjs'), `// generated by loader-boot-activation.test.mjs
export const name = 'loader-fixture-stub'
export function apply(ctx) {
  ctx.provide('sessions', { flush: async () => true })
  ctx.provide('sessionController', {
    resolveAgent: async sessionId => ({ agent: { session: { id: sessionId }, followup() {} } }),
    prompt: async () => ({ accepted: true }),
  })
${qqbot}}
`, 'utf8')

  // A relative specifier: from <fixture>/cordis.yml to <project>/lib/index.js.
  const entry = relative(dir, join(BRIDGE_ROOT, 'lib', 'index.js')).split(sep).join('/')
  await writeFile(join(dir, 'cordis.yml'), [
    '- id: loader-fixture-stub',
    '  name: ./stub.mjs',
    '- id: qqbot-bridge',
    `  name: ${entry}`,
    '  config:',
    `    statePath: ${JSON.stringify(statePath.replace(/\\/g, '/'))}`,
    `    dataDir: ${JSON.stringify(dataDir.replace(/\\/g, '/'))}`,
    '    allowOpenIds: []',
    '    defaultBot: 管家',
    '    allowGroups: false',
    `    watchdogIntervalMs: ${String(watchdogIntervalMs ?? 10_000)}`,
    '    debug: false',
    '',
  ].join('\n'), 'utf8')

  return {
    dir,
    configPath: join(dir, 'cordis.yml'),
    dataDir,
    statePath,
    statusPath: join(dataDir, 'bridge-status.json'),
    cleanup: () => rm(dir, { recursive: true, force: true }).catch(() => {}),
  }
}

/**
 * Collect everything the plugin writes to the console while `fn` runs.
 *
 * The default node:test reporter writes through `process.stdout`, not
 * `console.log`, so this window does not swallow test output -- and it must not
 * forward, or "the line was printed" would be untestable.
 */
const withConsoleCapture = async fn => {
  const lines = []
  const original = { log: console.log, warn: console.warn, error: console.error }
  for (const level of ['log', 'warn', 'error']) {
    console[level] = (...args) => {
      lines.push(args.map(value => (typeof value === 'string' ? value : JSON.stringify(value))).join(' '))
    }
  }
  try {
    return { lines, value: await fn() }
  } finally {
    Object.assign(console, original)
  }
}

const bridgeLines = lines => lines.filter(line => line.startsWith('[qqbot-bridge]'))

/** Wait until the bridge reports itself wired, or give up. */
const waitForBridge = async (ctx, { attempts = 200, delayMs = 10 } = {}) => {
  const service = ctx.get('qqbotBridge', false)
  for (let attempt = 0; attempt < attempts && service?.available !== true; attempt += 1) {
    await new Promise(resolve => setTimeout(resolve, delayMs))
  }
  return service
}

/** Wait until the on-disk status document reaches `phase`, or give up. */
const waitForPhase = async (statusPath, phase, { attempts = 200, delayMs = 10 } = {}) => {
  let seen
  for (let attempt = 0; attempt < attempts; attempt += 1) {
    try {
      seen = JSON.parse(await readFile(statusPath, 'utf8'))
      if (seen.phase === phase) return seen
    } catch {
      // not written yet
    }
    await new Promise(resolve => setTimeout(resolve, delayMs))
  }
  return seen
}

test('the real Loader activates the bridge and it announces itself on the console', { skip }, async () => {
  const fixture = await makeFixture({ withQqbot: true })
  let ctx
  try {
    const { boot } = await loadAppBoot()
    const captured = await withConsoleCapture(async () => {
      ctx = await boot('loader-test', fixture.configPath)
      // `boot()` settles the loader tree; bring-up itself is asynchronous, so
      // wait for the bridge the same way an operator waits for a log line.
      const service = await waitForBridge(ctx)
      // `available` flips before the status snapshot is written and the STARTED
      // line is printed; let those two land inside the capture window.
      await waitForPhase(fixture.statusPath, 'running')
      return service
    })
    const service = captured.value

    const lines = bridgeLines(captured.lines)
    assert.ok(lines.length > 0, 'the bridge must write to the console; ctx.logger alone is invisible in dsh web')
    assert.ok(
      lines.some(line => line.includes('apply() entered')),
      `apply() must announce itself. Got:\n${lines.join('\n')}`,
    )
    assert.ok(lines.some(line => line.includes('provided the "qqbotBridge" service')))
    assert.ok(
      lines.some(line => line.includes('STARTED:') && line.includes('dsh-qqbot-bridge/qq')),
      `the started line must name the borrowed transport. Got:\n${lines.join('\n')}`,
    )

    // The entry really is active, not merely present in the config.
    const entry = [...ctx.loader.entries()].find(candidate => candidate.options.id === 'qqbot-bridge')
    assert.ok(entry !== undefined)
    assert.equal(entry.fiber?.state, 2, 'the loader fiber must be ACTIVE (2)')

    assert.ok(service !== undefined, 'the bridge must publish the qqbotBridge service')
    assert.equal(service.available, true)
    assert.equal(service.transportOk, true)

    // ...and the on-disk record agrees with the console.
    const status = JSON.parse(await readFile(fixture.statusPath, 'utf8'))
    assert.equal(status.phase, 'running')
    assert.equal(status.available, true)
    assert.equal(status.transportOk, true)
    assert.equal(status.transport, 'dsh-qqbot-bridge/qq')
    assert.equal(status.allowOpenIdsCount, 0)
    assert.equal(status.failClosed, true, 'an empty allowlist must be recorded as fail-closed')
    assert.equal(status.statePath.replace(/\\/g, '/'), fixture.statePath.replace(/\\/g, '/'))
    assert.equal(status.bots.length, 4, 'the four Bots must come from the state file')
    assert.ok(!Number.isNaN(Date.parse(status.updatedAt)), 'updatedAt must be an ISO timestamp')
    assert.ok(!Number.isNaN(Date.parse(status.startedAt)))
    // Nothing in the document may be a credential.
    const text = JSON.stringify(status)
    assert.ok(!/appSecret|secret|token/i.test(text), `the status document must hold no credential-shaped field: ${text}`)
  } finally {
    await ctx?.fiber.dispose()
    await fixture.cleanup()
  }
})

test('a missing gateway service is announced by name instead of hanging in silence', { skip }, async () => {
  const fixture = await makeFixture({ withQqbot: false, watchdogIntervalMs: 40 })
  let ctx
  try {
    const { boot } = await loadAppBoot()
    const captured = await withConsoleCapture(async () => {
      ctx = await boot('loader-test', fixture.configPath)
      // Give the watchdog a couple of intervals to fire.
      await new Promise(resolve => setTimeout(resolve, 150))
      return ctx
    })

    const lines = bridgeLines(captured.lines)
    assert.ok(
      lines.some(line => line.includes('waiting for service(s): sessionController, sessions, qqbot')),
      `the wait must be announced. Got:\n${lines.join('\n')}`,
    )
    assert.ok(
      lines.some(line => line.includes('still waiting for service(s):')), 
      `the watchdog must repeat the wait. Got:\n${lines.join('\n')}`,
    )
    assert.ok(
      !lines.some(line => line.includes('STARTED:')),
      'the bridge must not claim to have started without its transport',
    )

    const service = ctx.get('qqbotBridge', false)
    assert.equal(service.available, false)
    assert.deepEqual(service.waitingFor(), ['qqbot'])

    const status = JSON.parse(await readFile(fixture.statusPath, 'utf8'))
    assert.equal(status.phase, 'waiting')
    assert.deepEqual(status.waitingFor, ['qqbot'])
    assert.equal(status.available, false)
  } finally {
    await ctx?.fiber.dispose()
    await fixture.cleanup()
  }
})

test('unloading the bridge records a stopped phase and unregisters the service', { skip }, async () => {
  const fixture = await makeFixture({ withQqbot: true })
  const { boot } = await loadAppBoot()
  const ctx = await boot('loader-test', fixture.configPath)
  try {
    assert.ok(ctx.get('qqbotBridge', false) !== undefined)
    // Let bring-up finish first, so this exercises a real unload rather than a
    // teardown racing a half-started bridge.
    await waitForBridge(ctx)
    await waitForPhase(fixture.statusPath, 'running')
    await ctx.fiber.dispose()
    assert.equal(ctx.get('qqbotBridge', false), undefined, 'teardown must unregister qqbotBridge')
    const status = await waitForPhase(fixture.statusPath, 'stopped')
    assert.equal(status.phase, 'stopped')
  } finally {
    await fixture.cleanup()
  }
})

test('the fixture generator leaves nothing behind', { skip }, async () => {
  const fixture = await makeFixture({ withQqbot: false })
  assert.ok(existsSync(fixture.configPath))
  await fixture.cleanup()
  assert.equal(existsSync(fixture.dir), false)
})
